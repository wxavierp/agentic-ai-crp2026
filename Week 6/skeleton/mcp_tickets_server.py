import itertools
from mcp.server.fastmcp import FastMCP

mcp = FastMCP("lumo-tickets")

_next_id = itertools.count(4821)
TICKETS = [
    {"id": "T-4818", "order": "LM-1004", "subject": "address could not be verified", "state": "open"},
    {"id": "T-4819", "order": "LM-1002", "subject": "customer asked to change the delivery day", "state": "open"},
    {"id": "T-4820", "order": "LM-1003", "subject": "headset arrived with a cracked case", "state": "closed"},
]


@mcp.tool()
def open_ticket(order_id: str, subject: str) -> str:
    """Open a support ticket for a customer about one order. Use this when the customer has a problem
    that cannot be answered by looking something up - a complaint, damage, or a change they want made.
    Returns the new ticket id."""
    ticket = {"id": "T-%d" % next(_next_id), "order": order_id.strip().upper(),
              "subject": subject.strip(), "state": "open"}
    TICKETS.append(ticket)
    return "Opened ticket %s for order %s: %s" % (ticket["id"], ticket["order"], ticket["subject"])


@mcp.tool()
def list_tickets(order_id: str) -> str:
    """List the support tickets already raised for one order id, with their state. Use this before
    opening a new ticket, so the customer is not told the same thing twice."""
    found = [t for t in TICKETS if t["order"] == order_id.strip().upper()]
    if not found:
        return "NO_TICKETS: nothing has been raised for order %s" % order_id.strip().upper()
    return "\n".join("%s (%s): %s" % (t["id"], t["state"], t["subject"]) for t in found)


mcp.run(transport="stdio")
