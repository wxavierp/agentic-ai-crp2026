"""
n8n_kit.py - call an n8n workflow from Python (you do NOT edit this file).

    from utils.n8n_kit import post_to_n8n, N8N_URL, USING

    post_to_n8n({"order_id": "LM-1004", "reason": "cracked case"})   # -> dict

If N8N_WEBHOOK_URL is set in your .env, this posts to YOUR workflow and returns whatever your
"Respond to Webhook" node sends back. If it is not set, a local stand-in answers in the same shape, so
the lab is never blocked by a sign-up. The stand-in is NOT n8n: it proves your code is right, not that
your workflow is.

Two things that catch everybody once:
  * A webhook has TWO urls. /webhook-test/... only fires while you are sitting in the editor with
    "Listen for test event" on, and it fires ONCE. /webhook/... works whenever the workflow is active.
    Put the PRODUCTION url in your .env.
  * The workflow must be published/active, or the production url returns 404.
"""
import json, os, itertools
from dotenv import load_dotenv

load_dotenv()
N8N_URL = os.getenv("N8N_WEBHOOK_URL", "").strip()
TIMEOUT = float(os.getenv("N8N_TIMEOUT", "10"))
USING = "your n8n workflow at %s" % N8N_URL if N8N_URL else "a local stand-in (set N8N_WEBHOOK_URL in .env to use real n8n)"

_counter = itertools.count(7001)


def _standin(payload):
    """What a sensible n8n workflow would send back, so the Python side can be finished and tested."""
    if not payload.get("order_id"):
        return {"ok": False, "error": "order_id is required"}
    return {"ok": True, "ticket": "N8N-%d" % next(_counter),
            "order_id": payload.get("order_id"),
            "queue": "human-support",
            "message": "A human has been notified and will reply by email."}


def post_to_n8n(payload, url=None, timeout=None):
    """POST a JSON payload to the workflow. Always returns a dict - never raises."""
    target = (url or N8N_URL).strip()
    if not target:
        return dict(_standin(payload), via="stand-in")
    import requests
    try:
        r = requests.post(target, json=payload, timeout=timeout or TIMEOUT)
    except Exception as e:                      # no network, bad host, timeout
        return {"ok": False, "error": "could not reach n8n: %s" % type(e).__name__, "via": "error"}
    if r.status_code == 404:
        return {"ok": False, "via": "error",
                "error": "404 from n8n - the workflow is not active, or this is a test url that has already fired"}
    if r.status_code >= 400:
        return {"ok": False, "via": "error", "error": "n8n returned HTTP %d: %s" % (r.status_code, r.text[:120])}
    try:
        body = r.json()
    except ValueError:
        return {"ok": True, "via": "n8n", "message": r.text[:300],
                "note": "the workflow did not return JSON - add a 'Respond to Webhook' node"}
    if isinstance(body, list) and body:         # n8n often responds with a list of items
        body = body[0]
    if not isinstance(body, dict):
        body = {"message": str(body)}
    return dict(body, via="n8n")
