"""
crew_kit.py - CrewAI, with a small plain-Python stand-in if it will not install (you do NOT edit this file).

    from utils.crew_kit import Agent, Task, Crew, Process, USING

It gives you the real CrewAI classes. If `pip install crewai` failed, it falls back to a small version with the
same five names and the same arguments, so the labs run either way. The stand-in supports exactly what the labs
use - and nothing more:

    Agent(role=, goal=, backstory=)
    Task(description=, expected_output=, agent=, context=[...], async_execution=True/False)
    Crew(agents=[...], tasks=[...], process=Process.sequential, verbose=False)
    crew.kickoff(inputs={...})      ->  result.raw  and  result.tasks_output[i].raw

Process.hierarchical needs  manager_agent=  : one extra agent that reads the task and picks who does it.
"""
import os, sys, time
from concurrent.futures import ThreadPoolExecutor

try:
    from crewai import Agent, Task, Crew, Process                     # noqa: F401
    USING = "crewai"
except Exception:                                                     # ImportError, or a broken install
    USING = "plain-Python stand-in (pip install crewai to use the real one)"

    sys.path.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    from utils.llm_client import LLMClient

    _client = LLMClient()

    class Process:
        sequential = "sequential"
        hierarchical = "hierarchical"

    class Agent:
        def __init__(self, role="", goal="", backstory="", verbose=False, allow_delegation=False, **kw):
            self.role, self.goal, self.backstory = role, goal, backstory
            self.verbose = verbose

        @property
        def rules(self):
            return "You are the %s.\nYour goal: %s\n%s\nAnswer with the finished work only - no preamble." % (
                self.role, self.goal, self.backstory)

        def run(self, description, expected_output, context_text):
            message = description
            if context_text:
                message += "\n\nWork handed to you by the others:\n" + context_text
            message += "\n\nWhat your answer must be: " + expected_output
            return _client.get_completion(message, system_message=self.rules, temperature=0)

    class TaskOutput:
        def __init__(self, raw, task):
            self.raw, self.task = raw, task
            self.agent = task.agent.role if task.agent else ""

        def __str__(self): return self.raw

    class Task:
        def __init__(self, description="", expected_output="", agent=None, context=None,
                     async_execution=False, **kw):
            self.description, self.expected_output = description, expected_output
            self.agent, self.context = agent, list(context or [])
            self.async_execution = async_execution
            self.output = None

    class CrewOutput:
        def __init__(self, outputs):
            self.tasks_output = outputs
            self.raw = outputs[-1].raw if outputs else ""

        def __str__(self): return self.raw

    class Crew:
        def __init__(self, agents=None, tasks=None, process=Process.sequential, verbose=False,
                     manager_agent=None, manager_llm=None, **kw):
            self.agents, self.tasks = list(agents or []), list(tasks or [])
            self.process, self.verbose = process, verbose
            self.manager_agent = manager_agent

        def _fill(self, text, inputs):
            for k, v in (inputs or {}).items():
                text = text.replace("{%s}" % k, str(v))
            return text

        def _pick(self, task, inputs):
            """hierarchical: the manager reads the task and names the agent who should do it."""
            names = [a.role for a in self.agents]
            rules = ("You are the %s. You do not do the work yourself. Read the task and answer with the "
                     "name of exactly ONE of these team members, and nothing else:\n%s" %
                     (self.manager_agent.role if self.manager_agent else "Manager", "\n".join(names)))
            said = _client.get_completion(self._fill(task.description, inputs), system_message=rules,
                                          temperature=0).strip()
            for a in self.agents:                                     # safe default: the task's own agent
                if a.role.lower() in said.lower():
                    return a, said
            return task.agent or self.agents[0], said

        def _run_one(self, task, inputs):
            context_text = "\n\n".join("[%s]\n%s" % (t.agent.role if t.agent else "", t.output.raw)
                                       for t in task.context if t.output)
            agent = task.agent
            note = ""
            if self.process == Process.hierarchical:
                agent, said = self._pick(task, inputs)
                note = "   manager picked: %s (said %r)" % (agent.role, said)
            if self.verbose:
                print("   -> %s" % agent.role + note)
            raw = agent.run(self._fill(task.description, inputs), task.expected_output, context_text)
            task.output = TaskOutput(raw, task)
            return task.output

        def kickoff(self, inputs=None):
            outputs, batch = [], []

            def flush():
                if not batch:
                    return
                if len(batch) == 1:
                    outputs.append(self._run_one(batch[0], inputs))
                else:
                    with ThreadPoolExecutor(max_workers=len(batch)) as pool:
                        outputs.extend(pool.map(lambda t: self._run_one(t, inputs), batch))
                batch.clear()

            for task in self.tasks:
                if task.async_execution:
                    batch.append(task)
                else:
                    flush()
                    outputs.append(self._run_one(task, inputs))
            flush()
            return CrewOutput(outputs)
