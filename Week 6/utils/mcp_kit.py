"""
mcp_kit.py - talk to an MCP server without writing any asyncio (you do NOT edit this file).

    from utils.mcp_kit import McpServer

    server = McpServer("13_mcp_server.py")       # starts it as a subprocess and keeps it running
    server.name                                  # what the server calls itself
    server.tools                                 # [{"name", "description", "schema"}, ...]  <- IT TOLD YOU THIS
    server.call("search_knowledge", question="E-4210")   # -> text
    server.stop()

The real MCP client API is asynchronous. Everything async is hidden in here: one event loop runs in a
background thread and the three methods above are ordinary blocking calls. When you write your own MCP
client later, read this file - it is forty lines and it is the whole pattern.
"""
import asyncio, os, sys, threading


class McpServer:
    def __init__(self, script, python=None, cwd=None, name=None, env=None):
        from mcp import StdioServerParameters
        self.script = script
        # NOTE worth knowing: an MCP stdio server is a SEPARATE PROCESS, and by default the protocol gives
        # it only a safe subset of your environment - not your whole shell. We pass the parent environment
        # through here so that a key you exported in your terminal still reaches the server. In production
        # you would do the opposite: hand the server exactly the variables it needs and nothing else.
        self._params = StdioServerParameters(command=python or sys.executable, args=[script],
                                             cwd=cwd or os.path.dirname(os.path.abspath(script)) or ".",
                                             env=dict(os.environ, **(env or {})))
        self._loop = asyncio.new_event_loop()
        self._thread = threading.Thread(target=self._loop.run_forever, daemon=True)
        self._thread.start()
        self._ready = threading.Event()
        self._stop = asyncio.Event()
        self.name, self.version, self.tools, self._error = name or script, "", [], None
        asyncio.run_coroutine_threadsafe(self._serve(), self._loop)
        if not self._ready.wait(timeout=60) or self._error:
            raise RuntimeError("could not start the MCP server %r: %s" % (script, self._error))

    async def _serve(self):
        """Keep one session open for the life of this object."""
        from mcp import ClientSession
        from mcp.client.stdio import stdio_client
        try:
            async with stdio_client(self._params) as (read, write):
                async with ClientSession(read, write) as session:
                    info = await session.initialize()
                    self.name = info.serverInfo.name
                    self.version = info.serverInfo.version
                    listed = await session.list_tools()
                    self.tools = [{"name": t.name, "description": t.description or "",
                                   "schema": t.inputSchema} for t in listed.tools]
                    self._session = session
                    self._ready.set()
                    await self._stop.wait()
        except Exception as e:                                   # the server crashed or would not start
            self._error = "%s: %s" % (type(e).__name__, e)
            self._ready.set()

    def call(self, tool_name, **arguments):
        """Call a tool on the server and get its text back."""
        async def go():
            out = await self._session.call_tool(tool_name, arguments)
            parts = [getattr(c, "text", "") for c in out.content]
            return "\n".join(p for p in parts if p)
        return asyncio.run_coroutine_threadsafe(go(), self._loop).result(timeout=120)

    def stop(self):
        self._loop.call_soon_threadsafe(self._stop.set)

    def describe(self):
        """A readable print of what the server said about itself."""
        lines = ["server: %s %s" % (self.name, self.version), "tools it offers:"]
        for t in self.tools:
            props = (t["schema"] or {}).get("properties", {})
            required = set((t["schema"] or {}).get("required", []))
            args = ", ".join("%s: %s%s" % (k, v.get("type", "?"), "" if k in required else " (optional)")
                             for k, v in props.items())
            lines.append("  %s(%s)" % (t["name"], args))
            lines.append("      %s" % t["description"].strip().split("\n")[0])
        return "\n".join(lines)
