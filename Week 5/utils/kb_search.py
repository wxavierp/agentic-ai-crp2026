"""
kb_search.py - the search from Day 14, ready to use (you do NOT edit this file).

    kb = KnowledgeBase(chunks)          # chunks = [{"id": ..., "text": ...}, ...]
    kb.search("The display says E-4210")   # -> [(chunk id, text), ...]  best first

Two steps, exactly as in 03_rerank.py:
  step 1  vector search          -> the 10 closest chunks (OpenAI embeddings)
  step 2  re-rank with keywords  -> mixed = 0.75 * vector score + 0.25 * keyword score, keep the best k
"""
import re
import numpy as np
from utils.llm_client import LLMClient

STOP = set("a an the is are was were be been to of in on for and or it its my i me do does did can could how what when where "
           "which who whom with at by from this that there their your you we our if as will would should may might any some "
           "up out so than then them they he she his her us have has had get got".split())


def words(text):
    """The important words of a text (small words like 'the' are dropped)."""
    return [w for w in re.findall(r"[a-z0-9]+", text.lower().replace("-", " ")) if w not in STOP]


class KnowledgeBase:
    def __init__(self, chunks, weight=0.25, candidates=10):
        self.chunks = chunks
        self.weight = weight
        self.candidates = candidates
        self.client = LLMClient(provider="openai")           # embeddings always come from OpenAI
        vectors = np.array(self.client.embed([c["text"] for c in chunks]))
        self.vectors = vectors / np.linalg.norm(vectors, axis=1, keepdims=True)

    def search(self, question, k=3):
        q = np.array(self.client.embed(question)[0])
        q /= np.linalg.norm(q)
        scores = self.vectors @ q
        best = np.argsort(-scores)[:self.candidates]                      # step 1: 10 candidates
        qwords = set(words(question))
        mixed = []
        for i in best:                                                    # step 2: re-rank
            share = len(qwords & set(words(self.chunks[i]["text"]))) / len(qwords) if qwords else 0
            mixed.append(((1 - self.weight) * scores[i] + self.weight * share, i))
        mixed.sort(reverse=True)
        return [(self.chunks[i]["id"], self.chunks[i]["text"]) for _, i in mixed[:k]]
