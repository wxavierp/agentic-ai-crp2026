"""
graph_kit.py - a tiny graph helper, ready to use (you do NOT edit this file).

    from utils.graph_kit import StateGraph, END, USING

It gives you the LangGraph classes. If langgraph is not installed (pip install langgraph), it falls back to a small
plain-Python version with the same five calls, so the labs run either way:

    graph = StateGraph(State)                       # a graph whose state is a dict
    graph.add_node("name", function)                # a node = a function: state in, the changed keys out
    graph.set_entry_point("name")                   # where the run starts
    graph.add_edge("a", "b")                        # after a, go to b          (END = stop)
    graph.add_conditional_edges("a", router, {"x": "b", "y": END})    # after a, ask router(state) which way to go
    workflow = graph.compile()
    workflow.invoke({...})                          # run it, get the final state
"""
try:
    from langgraph.graph import StateGraph, END
    USING = "langgraph"
except ImportError:
    USING = "plain-Python fallback (pip install langgraph to use the real one)"
    END = "__end__"

    class StateGraph:
        def __init__(self, schema=None):
            self.nodes, self.edges, self.routes, self.entry = {}, {}, {}, None

        def add_node(self, name, function):
            self.nodes[name] = function

        def set_entry_point(self, name):
            self.entry = name

        def add_edge(self, start, end):
            self.edges[start] = end

        def add_conditional_edges(self, start, router, mapping=None):
            self.routes[start] = (router, mapping)

        def compile(self):
            return self

        def invoke(self, state):
            state, node = dict(state), self.entry
            for _ in range(25):                                   # the same safety limit as langgraph
                if node == END:
                    return state
                state.update(self.nodes[node](state) or {})
                if node in self.routes:
                    router, mapping = self.routes[node]
                    key = router(state)
                    node = mapping[key] if mapping else key
                else:
                    node = self.edges[node]
            raise RuntimeError("the graph ran more than 25 steps (a loop with no stop rule?)")
